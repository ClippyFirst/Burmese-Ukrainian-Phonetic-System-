import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const readCsv = (rel) => {
  const text = fs.readFileSync(path.join(root, rel), "utf8").replace(/^\uFEFF/, "");
  const lines = text.trimEnd().split(/\r?\n/);
  const headers = lines.shift().split(",");
  return lines.map((line) => {
    const cells=[]; let cell=""; let quoted=false;
    for(let i=0;i<line.length;i++){
      const ch=line[i];
      if(ch === '"' && line[i+1] === '"' && quoted){cell+='"';i++;continue;}
      if(ch === '"'){quoted=!quoted;continue;}
      if(ch === "," && !quoted){cells.push(cell);cell="";continue;}
      cell+=ch;
    }
    cells.push(cell);
    if(quoted) throw new Error("Unclosed CSV quote");
    return Object.fromEntries(headers.map((h,i)=>[h,cells[i]??""]));
  });
};

const outDir=path.join(root,"src","web","generated");
fs.mkdirSync(outDir,{recursive:true});
const practical=readCsv("data/burmese/ukrainian_practical.csv");
const rules=readCsv("data/burmese/practical_rules.csv");
const onsets=readCsv("data/burmese/ipa_onsets.csv");
const vowels=readCsv("data/burmese/ipa_vowels.csv");
const signs=readCsv("data/burmese/vowel_signs.csv");
const medials=readCsv("data/burmese/medials.csv");
const grouped=(rows,key)=>Object.fromEntries(rows.reduce((a,r)=>{(a[r[key]]??=[]).push(r);return a;},{}));
const js="// Generated by scripts/generate-web-data.mjs. Do not edit manually.\n"
 + "export const PRACTICAL="+JSON.stringify(grouped(practical,"burmese_ipa"),null,2)+";\n"
 + "export const RULES="+JSON.stringify(grouped(rules,"input"),null,2)+";\n"
 + "export const ONSETS="+JSON.stringify(Object.fromEntries(onsets.map(r=>[r.character,r])),null,2)+";\n"
 + "export const VOWELS="+JSON.stringify(Object.fromEntries(vowels.map(r=>[r.id,r])),null,2)+";\n"
 + "export const SIGNS="+JSON.stringify(Object.fromEntries(signs.map(r=>[r.character,r])),null,2)+";\n"
 + "export const MEDIALS="+JSON.stringify(Object.fromEntries(medials.map(r=>[r.character,r])),null,2)+";\n";
fs.writeFileSync(path.join(outDir,"data.js"),js);
